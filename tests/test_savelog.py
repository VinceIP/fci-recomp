"""Q22b save log: the UDATA path filter and the line format, from the toolkit diff.

The C lives in the toolkit (patches/runtime/0026-save-log.patch, applied and
regenerated by the reviewer), so the test extracts savelog.c from the diff,
compiles it with the host compiler and runs a small harness. Skips when the
diff or a host C compiler is absent; fails when the filter or the format
behaves differently from what the save log promises.
"""

from pathlib import Path
import shutil
import subprocess

import pytest

import patches

REPO = Path(__file__).resolve().parents[1]
DIFF = REPO / "patches" / "runtime" / "0026-save-log.patch"

HARNESS = r"""
#include <stdio.h>
#include "savelog.h"

static void show(const char* tag, const char* v)
{
    printf("%s %s\n", tag, v ? v : "(null)");
}

static void show_line(const char* tag, int n, char* buf)
{
    if (n < 0) { printf("%s (err)\n", tag); return; }
    buf[n] = 0;
    printf("%s %d %s\n", tag, n, buf);
}

int main(void)
{
    char buf[256];
    show("F1", savelog_udata_rel("\\Device\\Harddisk0\\Partition1\\UDATA\\55530008\\9FBDF33E7A0C\\profile.sav"));
    show("F2", savelog_udata_rel("\\Device\\Harddisk0\\Partition1\\udata\\x.sav"));
    show("F3", savelog_udata_rel("\\Device\\CdRom0\\common.dat"));
    show("F4", savelog_udata_rel("\\Device\\Harddisk0\\Partition1\\UDATA"));
    show("F5", savelog_udata_rel("\\Device\\Harddisk0\\Partition1\\UDATABIN\\x.sav"));
    show("F6", savelog_udata_rel("profile.sav"));
    show("F7", savelog_udata_rel("U:\\55530008\\9FBDF33E7A0C\\profile.sav"));
    show("F8", savelog_udata_rel("u:\\55530008\\x.sav"));
    show("F9", savelog_udata_rel("\\??\\U:\\55530008\\x.sav"));
    show("F10", savelog_udata_rel("T:\\55530008\\x.sav"));
    show("J1", savelog_join(buf, sizeof buf, "55530008\\9FBDF33E7A0C", "profile.sav") >= 0 ? buf : "(err)");
    show("J2", savelog_join(buf, sizeof buf, "root/", "\\child") >= 0 ? buf : "(err)");
    show("J3", savelog_join(buf, 4, "root", "child") >= 0 ? buf : "(err)");
    show_line("L1", savelog_line(buf, sizeof buf, 12345, "55530008/9FBDF33E7A0C/profile.sav",
                                 "closed, 6077 bytes in 3 writes, open 12 ms"), buf);
    show_line("L2", savelog_line(buf, 8, 1, "rel", "deleted"), buf);
    show("V1", savelog_close_verb(3, 0));
    show("V2", savelog_close_verb(1, 2));
    show("V3", savelog_close_verb(0, 1));
    show("V4", savelog_close_verb(0, 2));
    show("V5", savelog_close_verb(0, 0));
    show_line("L3", savelog_line(buf, sizeof buf, 2308964390ULL,
                                 "55530008\\TitleMeta.xbx",
                                 "created, 0 bytes in 0 writes, open 0 ms"), buf);
    show("C1", savelog_collapse(buf, sizeof buf, "9FBDF33E7A0C\\\\fcs0.fcs") >= 0 ? buf : "(err)");
    show("C2", savelog_collapse(buf, sizeof buf, "9FBDF33E7A0C/fcs0.fcs") >= 0 ? buf : "(err)");
    show("C3", savelog_collapse(buf, sizeof buf, "a\\\\b//c\\d") >= 0 ? buf : "(err)");
    show("C4", savelog_collapse(buf, sizeof buf, "single\\path") >= 0 ? buf : "(err)");
    show("C5", savelog_collapse(buf, 4, "ab\\\\cd") >= 0 ? buf : "(err)");
    return 0;
}
"""


@pytest.fixture(scope="module")
def savelog_output(tmp_path_factory):
    if not DIFF.exists():
        pytest.skip(f"no save log diff at {DIFF}")
    cc = shutil.which("cc") or shutil.which("gcc")
    if not cc:
        pytest.skip("no host C compiler")
    src = tmp_path_factory.mktemp("savelog")
    files = {}
    for path, hunks in patches.parse(DIFF.read_bytes()):
        if path in ("src/kernel/savelog.c", "src/kernel/savelog.h"):
            files[path] = patches.apply_hunks(b"", hunks, path)
    if "src/kernel/savelog.c" not in files:
        pytest.fail("savelog.c not in the save log diff")
    (src / "savelog.c").write_bytes(files["src/kernel/savelog.c"])
    (src / "savelog.h").write_bytes(files["src/kernel/savelog.h"])
    (src / "harness.c").write_text(HARNESS)
    exe = src / "harness"
    subprocess.run([cc, "-o", str(exe), str(src / "harness.c"), str(src / "savelog.c"), "-I", str(src)], check=True)
    return subprocess.run([str(exe)], capture_output=True, text=True, check=True).stdout


def _line(out, tag):
    for line in out.splitlines():
        if line.startswith(tag + " "):
            return line[len(tag) + 1 :]
    raise AssertionError(f"no {tag} line in the harness output")


def test_filter_accepts_a_save_path(savelog_output):
    assert _line(savelog_output, "F1") == "55530008\\9FBDF33E7A0C\\profile.sav"


def test_filter_is_case_insensitive(savelog_output):
    assert _line(savelog_output, "F2") == "x.sav"


def test_filter_rejects_paths_outside_udata(savelog_output):
    assert _line(savelog_output, "F3") == "(null)"


def test_filter_rejects_the_udata_directory_itself(savelog_output):
    assert _line(savelog_output, "F4") == "(null)"


def test_filter_match_is_segment_bounded(savelog_output):
    assert _line(savelog_output, "F5") == "(null)"


def test_filter_rejects_bare_names(savelog_output):
    assert _line(savelog_output, "F6") == "(null)"


def test_filter_accepts_the_u_drive_form(savelog_output):
    # The game opens profile files via the U: drive letter, the same partition
    # as the device path -- the log must not go quiet on those.
    assert _line(savelog_output, "F7") == "55530008\\9FBDF33E7A0C\\profile.sav"


def test_filter_u_drive_is_case_insensitive(savelog_output):
    assert _line(savelog_output, "F8") == "55530008\\x.sav"


def test_filter_u_drive_with_object_manager_prefix(savelog_output):
    assert _line(savelog_output, "F9") == "55530008\\x.sav"


def test_filter_rejects_other_drive_letters(savelog_output):
    assert _line(savelog_output, "F10") == "(null)"


def test_join_combines_root_and_child(savelog_output):
    assert _line(savelog_output, "J1") == "55530008\\9FBDF33E7A0C/profile.sav"
    assert _line(savelog_output, "J2") == "root/child"
    assert _line(savelog_output, "J3") == "(err)"


def test_line_format(savelog_output):
    expected = "[FCI] save @12345: 55530008/9FBDF33E7A0C/profile.sav closed, 6077 bytes in 3 writes, open 12 ms"
    n, _, body = _line(savelog_output, "L1").partition(" ")
    assert body == expected
    assert int(n) == len(expected) + 1  # + the trailing newline


def test_line_too_small_buffer(savelog_output):
    assert _line(savelog_output, "L2") == "(err)"


def test_close_verb_closed_when_written(savelog_output):
    assert _line(savelog_output, "V1") == "closed"
    assert _line(savelog_output, "V2") == "closed"


def test_close_verb_created_and_truncated(savelog_output):
    assert _line(savelog_output, "V3") == "created"
    assert _line(savelog_output, "V4") == "truncated"


def test_close_verb_no_line_for_unchanged_writeless_close(savelog_output):
    assert _line(savelog_output, "V5") == "(null)"


def test_created_line_format(savelog_output):
    expected = "[FCI] save @2308964390: 55530008\\TitleMeta.xbx created, 0 bytes in 0 writes, open 0 ms"
    n, _, body = _line(savelog_output, "L3").partition(" ")
    assert body == expected
    assert int(n) == len(expected) + 1  # + the trailing newline


def test_collapse_doubles_a_doubled_backslash(savelog_output):
    # The measured bug: the level-start delete read 9FBDF33E7A0C\\fcs0.fcs.
    assert _line(savelog_output, "C1") == "9FBDF33E7A0C\\fcs0.fcs"


def test_collapse_normalises_forward_slashes(savelog_output):
    # savelog_join emits a "/"; the log's separator is a backslash.
    assert _line(savelog_output, "C2") == "9FBDF33E7A0C\\fcs0.fcs"


def test_collapse_collapses_mixed_runs(savelog_output):
    assert _line(savelog_output, "C3") == "a\\b\\c\\d"


def test_collapse_leaves_a_clean_path(savelog_output):
    assert _line(savelog_output, "C4") == "single\\path"


def test_collapse_too_small_buffer(savelog_output):
    assert _line(savelog_output, "C5") == "(err)"
